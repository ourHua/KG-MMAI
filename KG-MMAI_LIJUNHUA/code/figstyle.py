def hgrid(ax, axis="y"):
    ax.grid(axis=axis, linewidth=0.6, color="#E2E2E2", zorder=0)
    ax.set_axisbelow(True)


def check_overlaps(fig, tol=0.5, verbose=True):
    """Report intersecting visible Text bounding boxes after rendering."""
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    items = []
    for ax in fig.axes:
        if not ax.axison:
            continue
        legend_texts = set()
        legend = ax.get_legend()
        if legend:
            legend_texts.update(id(t) for t in legend.get_texts())
        ticks = set(id(t) for t in ax.get_xticklabels() + ax.get_yticklabels())
        artists = (
            ax.texts + [ax.title, ax.xaxis.label, ax.yaxis.label]
            + ax.get_xticklabels() + ax.get_yticklabels()
        )
        for text in artists:
            if id(text) in legend_texts:
                continue
            if id(text) in ticks:
                tx, ty = text.get_position()
                if text in ax.get_xticklabels():
                    lo, hi = sorted(ax.get_xlim())
                    if not (lo - 1e-9 <= tx <= hi + 1e-9):
                        continue
                else:
                    lo, hi = sorted(ax.get_ylim())
                    if not (lo - 1e-9 <= ty <= hi + 1e-9):
                        continue
            label = text.get_text().strip()
            if not label or not text.get_visible():
                continue
            try:
                bb = text.get_window_extent(renderer)
            except Exception:
                continue
            if bb.width > 0 and bb.height > 0:
                items.append((label, bb))
    for text in fig.texts:
        label = text.get_text().strip()
        if label and text.get_visible():
            items.append((label, text.get_window_extent(renderer)))

    hits = []
    for (s1, b1), (s2, b2) in itertools.combinations(items, 2):
        dx = min(b1.x1, b2.x1) - max(b1.x0, b2.x0)
        dy = min(b1.y1, b2.y1) - max(b1.y0, b2.y0)
        if dx <= tol or dy <= tol:
            continue
        if s1 == s2 and abs(b1.x0 - b2.x0) < 1.0 and abs(b1.y0 - b2.y0) < 1.0:
            continue
        hits.append((s1[:34], s2[:34], round(dx, 1), round(dy, 1)))

    if verbose:
        if hits:
            print(f"    !! {len(hits)} text overlap(s)")
            for hit in hits[:12]:
                print(f"       '{hit[0]}' x '{hit[1]}' ({hit[2]}x{hit[3]} px)")
        else:
            print("    no text overlaps")
    return hits


def save(fig, path_stem, formats=("png", "pdf")):
    stem = _normalise_stem(path_stem)
    for ext in formats:
        fig.savefig(stem.with_suffix(f".{ext}"), format=ext)
    plt.close(fig)
    print(f"  wrote {stem}.{'/'.join(formats)}")


def save_checked(fig, path_stem, formats=("png", "pdf")):
    """Render, report text collisions, and write publication PNG/PDF assets."""
    stem = _normalise_stem(path_stem)
    hits = check_overlaps(fig)
    for ext in formats:
        fig.savefig(stem.with_suffix(f".{ext}"), format=ext)
    plt.close(fig)
    print(f"  wrote {stem}.{'/'.join(formats)}" +
          ("  [OVERLAPS PRESENT]" if hits else ""))
    return hits
