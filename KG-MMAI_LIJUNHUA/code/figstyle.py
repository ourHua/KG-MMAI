LEGACY_REDIRECT = {
    "fig06_ranking_robustness": "supplementary/supp_A_ranking_robustness",
    "fig07_relation_difficulty": "supplementary/supp_B_relation_difficulty_legacy",
    "fig08_small_sample": "supplementary/supp_C_small_sample_precision",
}


def _normalise_stem(path_stem):
    path = Path(path_stem)
    replacement = LEGACY_REDIRECT.get(path.name)
    if replacement is None:
        path.parent.mkdir(parents=True, exist_ok=True)
        return path
    redirected = path.parent / replacement
    redirected.parent.mkdir(parents=True, exist_ok=True)
    print(f"  redirecting legacy figure {path.name} -> {redirected.name}")
    return redirected


